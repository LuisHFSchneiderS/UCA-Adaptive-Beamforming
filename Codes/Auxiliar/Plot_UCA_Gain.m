%PLOT_UCA_GAIN Plot azimuth gain with an optional dipole overlay.
%   phi: azimuth [rad]; G_dBi: gain [dBi].
%   C: K-by-3 positions [m]; f: frequency [Hz]; lambda: wavelength [m].
%   L: dipole length [m]; b: wire radius [m]; R: UCA radius [m].
%   Pacc: accepted power [W].
%   showStructure: 'on'/'off'; structureFraction: relative overlay radius.
%   figUCA: figure handle.

function figUCA = Plot_UCA_Gain(phi, G_dBi, C, f, lambda, L, b, R, Pacc, ...
    showStructure, structureFraction)
    K = size(C, 1);
    elementSpacing = 2*R*sin(pi/K);
    showStructure = validatestring(showStructure, {'on', 'off'});

    gainColor = [0.08 0.38 0.68];
    elementColor = [0.90 0.39 0.12];
    inkColor = [0.16 0.20 0.26];
    gridColor = [0.65 0.69 0.74];

    gainFloor_dBi = -20;                             % Plot minimum [dBi].
    gainCeiling_dBi = max(5, 5*ceil(max(G_dBi)/5));     % Plot maximum [dBi].

    figUCA = figure('Name', 'RX UCA Design', 'NumberTitle', 'off', ...
        'Color', 'w', 'Position', [100 100 1180 700]);
    sgtitle(figUCA, sprintf('RX UCA Design | %.0f MHz', f/1e6), ...
        'FontName', 'Arial', 'FontSize', 17, 'FontWeight', 'bold', ...
        'Color', inkColor);

    gainAxes = polaraxes(figUCA, 'Units', 'normalized', ...
        'Position', [0.04 0.10 0.65 0.76]);
    gainLine = polarplot(gainAxes, phi, G_dBi, ...
        'Color', gainColor, 'LineWidth', 2.4, 'Tag', 'UCAGain');
    Configure_Polar_dB_Axes(gainAxes, gainLine, [gainFloor_dBi gainCeiling_dBi], 'dBi');
    gainAxes.ThetaZeroLocation = 'right';
    gainAxes.ThetaDir = 'counterclockwise';
    gainAxes.ThetaTick = 0:30:330;
    gainAxes.RAxisLocation = 75;
    gainAxes.FontName = 'Arial';
    gainAxes.FontSize = 11;
    gainAxes.Color = 'w';
    gainAxes.RColor = inkColor;
    gainAxes.ThetaColor = inkColor;
    gainAxes.GridColor = gridColor;
    gainAxes.GridAlpha = 0.40;
    grid(gainAxes, 'on');
    title(gainAxes, 'Radiation gain | \theta = 90^{\circ}', ...
        'FontSize', 13, 'FontWeight', 'normal', 'Color', inkColor);

    infoAxes = axes(figUCA, 'Units', 'normalized', ...
        'Position', [0.73 0.24 0.25 0.52]);
    axis(infoAxes, 'off');
    text(infoAxes, 0, 1, 'Design parameters', 'Units', 'normalized', ...
        'VerticalAlignment', 'top', 'FontName', 'Arial', 'FontSize', 12, ...
        'FontWeight', 'bold', 'Color', inkColor);
    designInfo = { ...
        sprintf('Elements: %d | L/\\lambda = %.2f', K, L/lambda), ...
        sprintf('Radius: %.2f mm (%.3g\\lambda)', 1e3*R, R/lambda), ...
        sprintf('Adjacent spacing: %.2f mm', 1e3*elementSpacing), ...
        sprintf('Wire radius: %.2f mm', 1e3*b), ...
        sprintf('Equivalent accepted power: %.2f W', Pacc), ...
        sprintf('Peak gain: %.3f dBi', max(G_dBi)), ...
        sprintf('Azimuth variation: %.4g dB', max(G_dBi)-min(G_dBi))};
    text(infoAxes, 0, 0.84, designInfo, 'Units', 'normalized', ...
        'VerticalAlignment', 'top', 'FontName', 'Arial', 'FontSize', 10.5, ...
        'Interpreter', 'tex', 'Color', inkColor);

    if strcmp(showStructure, 'on')
        structureLimit = (max(hypot(C(:,1), C(:,2))) + b)/structureFraction;
        structureAxes = axes(figUCA, 'Units', 'normalized', ...
            'Position', gainAxes.Position, 'PositionConstraint', 'innerposition', ...
            'XLim', [-structureLimit structureLimit], ...
            'YLim', [-structureLimit structureLimit], ...
            'DataAspectRatio', [1 1 1], 'Color', 'none', 'Visible', 'off', ...
            'HitTest', 'off', 'PickableParts', 'none', ...
            'HandleVisibility', 'off', 'Tag', 'UCAStructure');
        hold(structureAxes, 'on');

        for elementIndex = 1:K
            rectangle(structureAxes, ...
                'Position', [C(elementIndex,1)-b, C(elementIndex,2)-b, 2*b, 2*b], ...
                'Curvature', [1 1], 'FaceColor', elementColor, ...
                'EdgeColor', elementColor, 'LineWidth', 1.2, ...
                'HitTest', 'off', 'PickableParts', 'none', 'Tag', 'UCADipole');
            text(structureAxes, C(elementIndex,1), C(elementIndex,2), ...
                num2str(elementIndex), 'HorizontalAlignment', 'center', ...
                'VerticalAlignment', 'middle', 'FontName', 'Arial', ...
                'FontSize', 9, 'FontWeight', 'bold', 'Color', 'w', ...
                'HitTest', 'off', 'PickableParts', 'none', 'Tag', 'UCADipoleLabel');
        end

        radialLabels = string(gainAxes.RTickLabel);
        structureRadius_dBi = gainAxes.RLim(1) + structureFraction*diff(gainAxes.RLim);
        radialLabels(gainAxes.RTick <= structureRadius_dBi) = "";
        gainAxes.RTickLabel = radialLabels;
        text(infoAxes, 0, 0.30, 'Structure: scaled top view', 'Units', 'normalized', ...
            'FontName', 'Arial', 'FontSize', 10, 'Color', elementColor);
    end

    figUCA.CurrentAxes = gainAxes;
end
